"""Label exact connected regions of the supplied permitted-ground masks.

Four-neighbor connectivity is sufficient: every safe diagonal in Terrain.Path
has both orthogonal neighbors, so it never joins separate four-neighbor regions.
"""
from pathlib import Path
import sys,json,collections,array
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'.test-deps'));sys.path.insert(0,str(ROOT/'tools'))
from PIL import Image
from lupa.lua51 import LuaRuntime
from build_roads import encode_rows

def components(raw,w,h):
    labels=array.array('I',[0])*len(raw);regions=[]
    for seed,value in enumerate(raw):
        if not value or labels[seed]:continue
        id=len(regions)+1;q=collections.deque([seed]);labels[seed]=id;count=0;x0,x1=seed%w,seed%w;y0,y1=seed//w,seed//w
        while q:
            at=q.popleft();x,y=at%w,at//w;count+=1;x0=min(x0,x);x1=max(x1,x);y0=min(y0,y);y1=max(y1,y)
            for n in ((at-1 if x else -1),(at+1 if x+1<w else -1),(at-w if y else -1),(at+w if y+1<h else -1)):
                if n>=0 and raw[n] and not labels[n]:labels[n]=id;q.append(n)
        regions.append(dict(id=id,cells=count,x=x0,y=y0,w=x1-x0+1,h=y1-y0+1))
    return labels,regions

def decode_rows(rows,w,h):
    alphabet='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
    result=bytearray(w*h)
    for y in range(h):
        line=rows[y+1] or ''
        for x in range(min(w,len(line)*6)):
            result[y*w+x]=(alphabet.index(line[x//6])>>(5-x%6))&1
    return bytes(result)

def main():
    lua=LuaRuntime(unpack_returned_tuples=True);lua.execute('A={}')
    for file in ['Data/Terrain.lua','Data/GroundCorrections.lua']:lua.execute('assert(loadstring(...))("Mapperly",A)',(ROOT/file).read_text())
    result={};report=[]
    for id,z in lua.globals().A.TerrainData.zones.items():
        if z.status not in ('complete','partial'):continue
        im=Image.open(ROOT.parent/f'output/terrain-overlays-70959/{id}.png').convert('L');w,h=im.size
        patch=lua.globals().A.GroundCorrectionData.zones[id]
        if patch and (patch.w!=w or patch.h!=h or patch.baseSha256!=z.maskSha256):raise ValueError('Stale ground correction')
        # Read the exact runtime supplement, never a potentially stale PNG from
        # an earlier build with a different set of audited floor corridors.
        extra=decode_rows(patch.rows,w,h) if patch else bytes(w*h)
        raw=bytes(int(v in (128,255) or p) for v,p in zip(im.tobytes(),extra))
        labels,regions=components(raw,w,h);largest=max(regions,key=lambda r:r['cells'])['id'];exceptions=[]
        for r in regions:
            if r['id']==largest:continue
            mask=bytearray(r['w']*r['h'])
            for y in range(r['h']):
                for x in range(r['w']):
                    if labels[(y+r['y'])*w+x+r['x']]==r['id']:mask[y*r['w']+x]=255
            exceptions.append(dict(x=r['x'],y=r['y'],w=r['w'],h=r['h'],rows=encode_rows(mask,r['w'],r['h'])))
        result[id]=dict(w=w,h=h,baseSha256=z.maskSha256,groundSha256=patch.maskSha256 if patch else '',groundCells=patch.cells if patch else 0,exceptions=exceptions)
        report.append(dict(mapID=id,components=len(regions),exceptionCells=sum(r['cells'] for r in regions if r['id']!=largest)))
        print(id,z.name,len(regions),'regions',flush=True)
    def literal(v):
        if isinstance(v,dict):return '{'+','.join('['+literal(k)+']='+literal(x) for k,x in v.items())+'}'
        if isinstance(v,list):return '{'+','.join(literal(x) for x in v)+'}'
        return json.dumps(v)
    (ROOT/'Data/WalkingRegions.lua').write_text('-- Exact safe-diagonal ground connectivity. Generated by tools/build_walking_regions.py.\nlocal _,A=...\nA.WalkingRegionData='+literal(dict(version=1,build=70959,zones=result))+'\n')
    (ROOT.parent/'output/zone-crossings-70959/walking-regions.json').write_text(json.dumps(report,indent=2))
    print('Walking region data bytes',(ROOT/'Data/WalkingRegions.lua').stat().st_size)

if __name__=='__main__':main()
