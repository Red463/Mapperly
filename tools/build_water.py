"""Derive conservative dry cells from verified MH2O-preserving terrain artifacts.

The original read-only snapshot extraction is Gatherly/tools/build_terrain.py.
Its PNGs retain native liquid occupancy (128), missing geometry (64), ground
(255) and restricted ground (0). Cleanup never changes liquid/missing values.
We verify each full uncompressed source SHA against the shipped terrain mask
before retaining dry cells. No coastlines or elevations are guessed.
"""
from pathlib import Path
import hashlib,json,sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'.test-deps'))
from PIL import Image
from lupa.lua51 import LuaRuntime

def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def main():
    artifacts=ROOT.parent/'output/terrain-overlays-70959'
    l=LuaRuntime(unpack_returned_tuples=True);l.execute('A={}')
    l.execute('assert(loadstring(...))("Mapperly",A)',(ROOT/'Data/Terrain.lua').read_text())
    alpha='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
    lines=['-- Generated by tools/build_water.py; native ADT MH2O occupancy, see Water-SOURCES.md.',
           'local _,A=...','A.WaterData={version=1,build=70959,zones={}}','local Z=A.WaterData.zones']
    sources={};counts={}
    for mid,z in sorted(l.globals().A.TerrainData.zones.items()):
        if z.status not in ('complete','partial'):continue
        path=artifacts/f'{mid}.png'
        image=Image.open(path);raw=image.tobytes();w,h=image.size
        assert (w,h)==(z.w,z.h) and hashlib.sha256(raw).hexdigest()==z.maskSha256,f'Stale native artifact {mid}'
        assert set(raw)<={0,64,128,255}
        rows=[]
        for y in range(h):
            row=[]
            for x in range(0,w,6):
                value=0
                for bit in range(6):value=value*2+int(x+bit<w and raw[y*w+x+bit] in (0,255))
                row.append(alpha[value])
            rows.append(''.join(row))
        lines.append(f'Z[{mid}]={{w={w},h={h},baseSha256="{z.maskSha256}",rows={{')
        lines.extend(json.dumps(s)+',' for s in rows);lines.append('}}')
        sources[str(mid)]=dict(pngSha256=sha(path),nativeMaskSha256=z.maskSha256)
        counts[str(mid)]=dict(dry=sum(v in (0,255) for v in raw),liquid=raw.count(128),unknown=raw.count(64))
    target=ROOT/'Data/Water.lua';target.write_text('\n'.join(lines)+'\n',encoding='utf8')
    manifest=dict(version=1,build=70959,method='MH2O occupancy preserved by original terrain generator; 0/255 known nonliquid, 128 liquid, 64 unknown.',
      terrainSha256=sha(ROOT/'Data/Terrain.lua'),outputSha256=sha(target),
      sourceRulesSha256=sha(ROOT.parent/'Gatherly/tools/terrain/rules.py'),
      sourceGeneratorSha256=sha(ROOT.parent/'Gatherly/tools/build_terrain.py'),sources=sources,counts=counts)
    (ROOT/'tools/data/water-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Generated {len(sources)} local maps; {sum(v["liquid"] for v in counts.values())} liquid and {sum(v["unknown"] for v in counts.values())} unknown cells; {target.stat().st_size} bytes')

if __name__=='__main__':main()
