"""Build Mapperly's outdoor vendor and trainer directory from the pinned Forever SQL."""
from collections import Counter, defaultdict
import csv
import json
import subprocess

import build_quest_locations as locations
import build_services as services


# NPCFlags in Forever's UnitDefines.h. Some specialized vendors omit the generic bit.
VENDOR = 0x0F80
TRAINER = 0x0070
REPAIR = 0x1000
TABLES = {'creature_template', 'creature', 'game_event_creature', 'pool_members',
          'conditions', 'spawn_group', 'spawn_group_template'}
integer = locations.integer


def extract(rows, factions):
    templates = {}
    spawns = []
    excluded_guids = set()
    excluded_entries = set()
    excluded_groups = set()
    group_spawns = defaultdict(list)
    for table, row in rows:
        if table == 'creature_template':
            entry = integer(row, 'entry')
            templates[entry] = (row['name'], row.get('subname'), integer(row, 'npcflag'),
                                locations.faction_access(integer(row, 'faction'), factions),
                                integer(row, 'trainer_class'))
        elif table == 'creature':
            instance = integer(row, 'map')
            if (instance not in services.MAPS or (row.get('spawnDifficulties') or '0') != '0'
                    or integer(row, 'terrainSwapMap', -1) != -1
                    or any(integer(row, k) for k in ('PhaseId', 'PhaseGroup', 'phaseUseFlags'))):
                continue
            point = locations.coordinates(row)
            if point:
                spawns.append((integer(row, 'guid'), integer(row, 'id'), instance, point,
                               row.get('npcflag')))
        elif table == 'game_event_creature':
            excluded_guids.add(integer(row, 'guid'))
        elif table == 'pool_members' and integer(row, 'type') == 0:
            excluded_guids.add(integer(row, 'spawnId'))
        elif table == 'spawn_group' and integer(row, 'spawnType') == 0:
            group_spawns[integer(row, 'groupId')].append(integer(row, 'spawnId'))
        elif table == 'spawn_group_template' and integer(row, 'groupFlags') & (0x04 | 0x20):
            excluded_groups.add(integer(row, 'groupId'))
        elif table == 'conditions':
            kind, source = integer(row, 'SourceTypeOrReferenceId'), abs(integer(row, 'SourceEntry'))
            if kind == 32:
                excluded_entries.add(source)
            elif kind == 33:
                excluded_groups.add(source)

    for group in excluded_groups:
        excluded_guids.update(group_spawns[group])
    directory = defaultdict(dict)
    for guid, entry, instance, (east, north), override in spawns:
        if guid in excluded_guids or entry in excluded_entries or entry not in templates:
            continue
        name, specialty, flags, access, trainer_class = templates[entry]
        if not name or not access:
            continue
        if override is not None:
            flags = int(override)
        # Repair vendors already carry the capability on their merchant row.
        roles = [('vendor', VENDOR), ('trainer', TRAINER)]
        if flags & REPAIR and not flags & VENDOR:
            roles.append(('repair', REPAIR))
        for category, mask in roles:
            if flags & mask:
                record = dict(category=category, id=entry, name=name, x=north, y=east, access=access)
                if specialty:
                    record['specialty'] = specialty
                if category == 'vendor' and flags & REPAIR:
                    record['repairs'] = True
                if category == 'trainer' and trainer_class:
                    record['trainerClass'] = trainer_class
                directory[instance][category, entry, north, east] = record
    return {instance: [records[k] for k in sorted(records)] for instance, records in sorted(directory.items())}


def load_directory():
    archive = services.CACHE / services.ARCHIVE
    locations.verify(archive, services.SHA256)
    sql = services.CACHE / services.WORLD
    if not sql.exists():
        subprocess.run(['tar', '-xf', str(archive), '-C', str(services.CACHE), services.WORLD], check=True)
    locations.verify(sql, locations.SQL_SHA256)
    faction_csv = services.ROOT / 'tools/data/factiontemplate-70959.csv'
    locations.verify(faction_csv, '963a24a4a32acd76dea04ac337e037f45d72e2c6a403e3826dfcfc95e28b746d')
    with faction_csv.open(encoding='utf-8-sig', newline='') as source:
        factions = {int(row['ID']): row for row in csv.DictReader(source)}
    return extract(services.rows(sql, TABLES), factions)


def build():
    directory = load_directory()
    lines = ['-- Generated by tools/build_service_directory.py from Forever TDB 2026-10-14.',
             '-- GPL-2.0. See Data/ServiceDirectory-SOURCES.md and Libs/Forever-Services-COPYING.txt.',
             'local _,A=...', 'A.ServiceDirectory={']
    for instance, records in directory.items():
        lines.append(f' [{instance}]={{')
        for record in records:
            fields = [k + '=' + json.dumps(v, ensure_ascii=False) for k, v in record.items()]
            lines.append('  {' + ','.join(fields) + '},')
        lines.append(' },')
        print(instance, dict(Counter((r['category'], r['access']) for r in records)))
    lines.append('}')
    output = services.ROOT / 'Data/ServiceDirectory.lua'
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    build()
